// Generates supabase/seed.sql from the site's data files, so the database and the
// website always list the same products and prices.
// Run:  npm run db:seed-sql
import { writeFileSync, mkdirSync } from "node:fs";
import { PRODUCTS } from "../src/data/products";
import { EXPERIENCES } from "../src/data/tourism";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines: string[] = ["-- Generated by scripts/gen-seed.ts. Re-run safe (upserts).", ""];

for (const p of PRODUCTS) {
  lines.push(
    `insert into public.products (slug,name,category,sale_type,price,seller,location,community) values (` +
      `${q(p.slug)},${q(p.name)},${q(p.category)},${q(p.saleType)},${p.price},${q(p.seller)},${q(p.location)},${p.community}) ` +
      `on conflict (slug) do update set name=excluded.name, category=excluded.category, sale_type=excluded.sale_type, ` +
      `price=excluded.price, seller=excluded.seller, location=excluded.location, community=excluded.community;`,
  );
}
lines.push("");

for (const e of EXPERIENCES) {
  lines.push(
    `insert into public.experiences (slug,title,destination,price,provider) values (` +
      `${q(e.slug)},${q(e.title)},${q(e.destination)},${e.price},${q(e.provider)}) ` +
      `on conflict (slug) do update set title=excluded.title, destination=excluded.destination, price=excluded.price, provider=excluded.provider;`,
  );
}
lines.push("");

// Auctions: ends_at is set relative to "now" the first time this runs.
for (const p of PRODUCTS.filter((x) => x.saleType === "auction" && x.auction)) {
  lines.push(
    `insert into public.auctions (slug,current_bid,bid_count,ends_at) values (` +
      `${q(p.slug)},${p.auction!.currentBid},${p.auction!.bids},now() + interval '7 days') on conflict (slug) do nothing;`,
  );
}

mkdirSync("supabase", { recursive: true });
writeFileSync("supabase/seed.sql", lines.join("\n") + "\n");
console.log(`seed.sql: ${PRODUCTS.length} products, ${EXPERIENCES.length} experiences`);
